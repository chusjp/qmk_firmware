#!/usr/bin/env python3
"""Generates keymap_macros.h from macros.json for the enigma keymap.

Usage: python3 generate_keymap.py
Then:  qmk compile -kb enigma -km default   (and reflash)

Edit macros.json, re-run this script, recompile -- that's the whole loop.
Nothing here talks to the keyboard; it only regenerates a C header.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
KEYS = ["A", "B", "C", "D", "E"]  # matches the 5 macro-key positions in keymap.c
MAX_LAYERS = 4
EMPTY_NAME = "(unused)"

def c_string_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

def gen_action(action):
    if action.startswith("TAP:"):
        keycode = action[len("TAP:"):].strip()
        if not keycode:
            raise ValueError(f"empty keycode in action: {action!r}")
        return f"tap_code16({keycode});"
    return f'SEND_STRING("{c_string_escape(action)}");'

def main():
    config_path = HERE / "macros.json"
    config = json.loads(config_path.read_text())
    layers = config.get("layers")
    if not layers:
        sys.exit("macros.json needs a non-empty 'layers' list")
    if len(layers) > MAX_LAYERS:
        sys.exit(f"macros.json has {len(layers)} layers, but only {MAX_LAYERS} are supported")

    num_layers = len(layers)

    lines = []
    lines.append("// AUTO-GENERATED by generate_keymap.py from macros.json.")
    lines.append("// Do not edit by hand -- edit macros.json and re-run the script instead.")
    lines.append("")
    lines.append(f"#define NUM_MACRO_LAYERS {num_layers}")
    lines.append("")
    lines.append("enum custom_keycodes {")
    for i, k in enumerate(KEYS):
        lines.append(f"    MACRO_{k}{' = SAFE_RANGE' if i == 0 else ''},")
    for k in KEYS:
        lines.append(f"    INFO_{k},")
    lines.append("    CYCLE_LAYER,")
    lines.append("};")
    lines.append("")

    lines.append("static const char *key_descriptions[NUM_MACRO_LAYERS][5] = {")
    for layer in layers:
        keys = layer.get("keys", {})
        row = ", ".join(f'"{c_string_escape(keys[k]["name"])}"' if k in keys else f'"{EMPTY_NAME}"' for k in KEYS)
        lines.append(f"    {{{row}}},")
    lines.append("};")
    lines.append("")

    lines.append("static void run_macro(uint8_t layer, uint8_t index) {")
    lines.append("    switch (layer) {")
    for li, layer in enumerate(layers):
        keys = layer.get("keys", {})
        lines.append(f"        case {li}:")
        lines.append("            switch (index) {")
        for ki, k in enumerate(KEYS):
            if k not in keys:
                continue
            lines.append(f"                case {ki}: // {k}: {keys[k].get('name', '')}")
            for action in keys[k].get("actions", []):
                lines.append(f"                    {gen_action(action)}")
            lines.append("                    break;")
        lines.append("            }")
        lines.append("            break;")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    out_path = HERE / "keymap_macros.h"
    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_path} ({num_layers} layer(s))")

if __name__ == "__main__":
    main()
