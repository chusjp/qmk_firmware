#!/usr/bin/env python3
"""One-off tool: extracts the printable-ASCII glyphs QMK's built-in OLED
font (drivers/oled/glcdfont.c) already ships, and writes them out as our
own small PROGMEM table in keymap_bigfont.h, so keymap.c can render them
scaled up via oled_write_pixel (the original table is `static` to that
file, so it isn't reachable from a keymap directly).

Only needs to be re-run if drivers/oled/glcdfont.c itself changes.
"""
import re
from pathlib import Path

SRC = Path(__file__).resolve().parents[4] / "drivers" / "oled" / "glcdfont.c"
OUT = Path(__file__).parent / "keymap_bigfont.h"

line_re = re.compile(
    r"((?:0x[0-9A-Fa-f]{2},\s*){6})//\s*(0x[0-9A-Fa-f]{2})"
)

glyphs = {}
for line in SRC.read_text().splitlines():
    m = line_re.search(line)
    if not m:
        continue
    byte_strs = re.findall(r"0x[0-9A-Fa-f]{2}", m.group(1))
    codepoint = int(m.group(2), 16)
    glyphs[codepoint] = byte_strs[:5]  # drop the trailing 0x00 spacer column

FIRST, LAST = 0x20, 0x7E  # printable ASCII: space through '~'
missing = [cp for cp in range(FIRST, LAST + 1) if cp not in glyphs]
if missing:
    raise SystemExit(f"missing glyphs for codepoints: {missing}")

lines = []
lines.append("// AUTO-GENERATED by gen_bigfont.py from drivers/oled/glcdfont.c.")
lines.append("// Re-run that script if you need to regenerate this (the upstream font rarely changes).")
lines.append("")
lines.append("#define BIG_FONT_FIRST 0x20")
lines.append("#define BIG_FONT_LAST  0x7E")
lines.append("")
lines.append("static const unsigned char big_font[] PROGMEM = {")
for cp in range(FIRST, LAST + 1):
    b = ", ".join(glyphs[cp])
    ch = chr(cp) if chr(cp) != "\\" and chr(cp) != "'" else "?"
    lines.append(f"    {b}, // {cp:#04x} '{ch}'")
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(glyphs)} glyphs available, {LAST - FIRST + 1} exported)")
